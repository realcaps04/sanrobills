export const inventory: InventoryRow[] = products.map((p) => {
  const sales = Math.max(0, 40 - p.stock_quantity)
  const purchases = 40
  const opening = p.stock_quantity + sales - purchases + purchases
  let status: InventoryRow['status'] = 'in_stock'
  if (p.stock_quantity <= 0) status = 'out_of_stock'
  else if (p.stock_quantity <= p.minimum_stock) status = 'low_stock'

  return {
    id: `invt-${p.id}`,
    product_id: p.id,
    product_name: p.name,
    sku: p.product_code,
    opening_stock: opening,
    purchases,
    sales,
    current_stock: p.stock_quantity,
    minimum_stock: p.minimum_stock,
    status,
  }
})

